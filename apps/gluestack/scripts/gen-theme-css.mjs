// Generates theme.generated.css from shared/tokens.ts so the gluestack app's
// Tailwind v4 / Uniwind theme comes from the same tokens as every other app.
// Tailwind v4 is CSS-first: Uniwind reads global.css at bundle time and cannot
// import a TS module, hence this build step. Run: npm run tokens
// (Node >= 22.18 strips the TypeScript types on import.)
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

import { colors, radius, space, type } from '../../../shared/tokens.ts';

// gluestack-ui v5 semantic token  <-  shared token
// gluestack's components only know the shadcn-style names on the left, so the
// shared palette is mapped onto them; extra names keep tokens gluestack lacks.
const map = {
  background: 'background',
  foreground: 'text',
  card: 'surfaceRaised',
  popover: 'surfaceRaised',
  'popover-foreground': 'text',
  primary: 'primary',
  'primary-foreground': 'onPrimary',
  secondary: 'surface',
  'secondary-foreground': 'text',
  muted: 'surface',
  'muted-foreground': 'textMuted',
  accent: 'surface',
  'accent-foreground': 'text',
  destructive: 'danger',
  border: 'border',
  input: 'border',
  ring: 'focus',
  // Not in gluestack's default set:
  'destructive-foreground': 'onDanger',
  surface: 'surface',
  'surface-raised': 'surfaceRaised',
  success: 'success',
};

// gluestack stores colours as "R G B" triplets wrapped later in rgb(var(--x)).
const triplet = (hex) => {
  const h = hex.replace('#', '');
  return [0, 2, 4].map((i) => parseInt(h.slice(i, i + 2), 16)).join(' ');
};

const block = (name) => {
  const c = colors[name];
  const lines = Object.entries(map).map(([k, v]) => `      --${k}: ${triplet(c[v])};`);
  // scrim is rgba in the tokens, so it is kept as a full colour value.
  lines.push(`      --scrim: ${c.scrim};`);
  return `    @variant ${name} {\n${lines.join('\n')}\n    }`;
};

const colorUtilities = Object.keys(map)
  .map((k) => `  --color-${k}: rgb(var(--${k}));`)
  .concat('  --color-scrim: var(--scrim);')
  .join('\n');

const spacing = Object.entries(space).map(([k, v]) => `  --spacing-${k}: ${v}px;`);
// radius.full is left to Tailwind's own rounded-full.
const radii = Object.entries(radius)
  .filter(([k]) => k !== 'full')
  .map(([k, v]) => `  --radius-${k}: ${v}px;`);
const text = Object.entries(type).flatMap(([k, v]) => [
  `  --text-${k}: ${v.fontSize}px;`,
  `  --text-${k}--line-height: ${v.lineHeight}px;`,
  ...('fontWeight' in v ? [`  --text-${k}--font-weight: ${v.fontWeight};`] : []),
]);

const css = `/* GENERATED by scripts/gen-theme-css.mjs from shared/tokens.ts. Do not edit. */
/* Theme variants are switched at runtime with Uniwind.setTheme(), which
   gluestack's GluestackUIProvider calls from its \`mode\` prop. */
@layer theme {
  :root {
${['light', 'dark', 'brand'].map(block).join('\n\n')}
  }
}

@theme inline {
${colorUtilities}
}

@theme {
${[...spacing, ...radii, ...text].join('\n')}
}
`;

const out = fileURLToPath(new URL('../theme.generated.css', import.meta.url));
writeFileSync(out, css);
console.log(`wrote ${out}`);
